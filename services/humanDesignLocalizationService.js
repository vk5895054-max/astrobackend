const normalize = (value) => value.trim().toLowerCase().replace(/\s+/g, " ");

const translateText = (value) => {
  if (typeof value !== "string") return value;
  const normalized = normalize(value);
  if (HINDI_VALUES[normalized]) return HINDI_VALUES[normalized];
  if (TYPE_DESCRIPTIONS[normalized]) return TYPE_DESCRIPTIONS[normalized];

  const profile = normalized.match(/^([1-6]\/[1-6])\s+(.+)$/);
  if (profile && HINDI_VALUES[profile[2]]) {
    return `${profile[1]} ${HINDI_VALUES[profile[2]]}`;
  }

  for (const [prefix, hindi] of DESCRIPTION_PREFIXES) {
    if (normalized.startsWith(prefix)) return hindi;
  }

  const experience = normalized.match(/^experiencing (.+) indicates/);
  if (experience && HINDI_VALUES[experience[1]]) {
    return `${HINDI_VALUES[experience[1]]} का अनुभव इस बात का संकेत है कि आप अपनी रणनीति और आंतरिक मार्गदर्शन के अनुरूप हैं।`;
  }

  const gate = normalized.match(/^gate (\d+)$/);
  if (gate) return `द्वार ${gate[1]}`;
  const namedGate = normalized.match(/^(?:the )?gate of (.+)$/);
  if (namedGate) {
    const translatedName = HINDI_VALUES[normalized.replace(/^the /, "")];
    if (translatedName) return translatedName;
    if (HINDI_VALUES[namedGate[1]]) return `${HINDI_VALUES[namedGate[1]]} का द्वार`;
  }
  const channel = normalized.match(/^channel (\d+-\d+)$/);
  if (channel) return `मार्ग ${channel[1]}`;
  return value;
};

const clone = (value) => {
  if (Array.isArray(value)) return value.map(clone);
  if (value && typeof value === "object") {
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return value;
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, clone(item)]),
    );
  }
  return value;
};

const translateFields = (target, fields) => {
  if (!target || typeof target !== "object") return;
  for (const field of fields) {
    const value = target[field];
    if (typeof value === "string") target[field] = translateText(value);
    else if (Array.isArray(value)) {
      target[field] = value.map((item) =>
        typeof item === "string" ? translateText(item) : item,
      );
    }
  }
};

const localizeCenters = (centers) => {
  if (!Array.isArray(centers)) return;
  for (const center of centers) {
    translateFields(center, [
      "displayName",
      "statusLabel",
      "keywords",
      "keywordsText",
      "description",
    ]);
  }
};

const localizeGates = (gates) => {
  if (!Array.isArray(gates)) return;
  for (const gate of gates) {
    translateFields(gate, ["label", "name", "keynote", "description"]);
  }
};

const localizeChannels = (channels) => {
  if (!Array.isArray(channels)) return;
  for (const channel of channels) {
    translateFields(channel, ["title", "name", "description"]);
  }
};

const localizeEnvironment = (environment) => {
  translateFields(environment, ["name", "polarity", "label", "description"]);
  if (environment?.name && environment?.polarity) {
    environment.label = `${environment.name} (${environment.polarity})`;
  }
};

const localizeCross = (cross) => {
  translateFields(cross, ["angle", "name", "summary"]);
  if (typeof cross?.summary === "string") {
    cross.summary = cross.summary
      .replace(/\bSun\b/g, "सूर्य")
      .replace(/\bEarth\b/g, "पृथ्वी")
      .replace(/\bPersonality\b/g, "व्यक्तित्व")
      .replace(/\bDesign\b/g, "रचना");
  }
};

